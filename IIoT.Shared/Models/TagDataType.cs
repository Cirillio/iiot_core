namespace IIoT.Shared.Models;

/// <summary>
/// Тип данных тега (точки опроса).
/// Соответствует ENUM 'tag_data_type' в PostgreSQL.
/// Определяет способ обработки "сырых" данных.
/// </summary>
public enum TagDataType
{
    /// <summary>
    /// Сырое значение АЦП (например, ADAM-6017: 0-65535). Требует линейной интерполяции
    /// по границам Input/Output в физическую величину.
    /// </summary>
    AnalogRaw,

    /// <summary>
    /// Готовая физическая величина с интеллектуального прибора (Float32/64, напр. Меркурий).
    /// Десериализуется из регистров с учётом Endianness и возвращается как есть, без масштабирования.
    /// </summary>
    AnalogPhysical,

    /// <summary>
    /// Дискретный сигнал (0 или 1).
    /// </summary>
    Digital,

    /// <summary>
    /// Виртуальный тег (вычисляется по формуле из других тегов).
    /// </summary>
    Virtual,
}
